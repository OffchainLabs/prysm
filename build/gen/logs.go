package main

// This file generates the per-package log.go files: every package that
// references logrus gets a generated log.go declaring its package-scoped `log`
// variable, prefixed with the package path.
//

import (
	"bytes"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

// logrusImport is the import path whose presence makes a package want a log.go.
const logrusImport = "github.com/sirupsen/logrus"

// logsExcludedDirs are repo-relative paths that are never scanned, along with
// all their subdirectories.
var logsExcludedDirs = []string{
	"testing",
	"validator/client/testutil",
	"beacon-chain/p2p/testing",
	"beacon-chain/rpc/eth/config",
	"beacon-chain/rpc/prysm/v1alpha1/debug",
	"tools",
	"runtime/logging",
	"monitoring",
	"io",
	"changelog",
	"hack",
	"specrefs",
	"third_party",
	"build",
	"bin",
	"dist",
	"external",
	"bazel-bin",
	"bazel-out",
	"bazel-prysm",
	"bazel-testlogs",
}

// logsFileName is the generated file's name.
const logsFileName = "log.go"

func genLogs() error {
	_, dirs, err := logsScan()
	if err != nil {
		return fmt.Errorf("logsScan: %w", err)
	}

	written := 0
	for _, dir := range dirs {
		pkg, err := logsPkgName(dir)
		if err != nil {
			return fmt.Errorf("logsPkgName %s: %w", dir, err)
		}

		if pkg == "" {
			fmt.Printf("could not determine package name for %s, skipping\n", dir)
			continue
		}

		path := filepath.Join(dir, logsFileName)
		want := []byte(logsFileContent(pkg, filepath.ToSlash(dir)))

		got, err := os.ReadFile(path) // #nosec G304 -- path comes from the repo-relative scan
		if err != nil && !os.IsNotExist(err) {
			return fmt.Errorf("readFile %s: %w", path, err)
		}

		if bytes.Equal(got, want) {
			continue
		}

		if err := os.WriteFile(path, want, 0o600); err != nil {
			return fmt.Errorf("writeFile %s: %w", path, err)
		}

		fmt.Printf("wrote %s (package: %s)\n", path, pkg)
		written++
	}

	fmt.Printf("%d packages reference logrus, %d log.go files (re)written\n", len(dirs), written)

	return nil
}

func logsFileContent(pkg, relPath string) string {
	return fmt.Sprintf(`// Code generated by "make gen logs"; DO NOT EDIT.
// This file is created and regenerated automatically. Anything added here might get removed.
package %s

import "%s"

// The prefix for logs from this package will be the text after the last slash in the package path.
// If you wish to change this, you should add your desired name in the runtime/logging/logrus-prefixed-formatter/prefix-replacement.go file.
var log = logrus.WithField("package", "%s")
`, pkg, logrusImport, relPath)
}

// logsFiles returns every file the logs manifest depends on: all the scanned Go
// files, which includes the generated log.go outputs.
func logsFiles() ([]string, error) {
	files, _, err := logsScan()
	if err != nil {
		return nil, fmt.Errorf("logsScan: %w", err)
	}

	return files, nil
}

// logsScan walks the repo once and returns every scanned Go file plus the
// sorted directories holding at least one file that references logrus.
//
// Scanned means: a non-test .go file outside logsExcludedDirs and outside any
// hidden directory.
func logsScan() (files, dirs []string, err error) {
	seen := make(map[string]bool)

	err = filepath.WalkDir(".", func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return fmt.Errorf("walkDir %s: %w", path, err)
		}

		rel := filepath.ToSlash(path)
		if d.IsDir() {
			if rel != "." && (logsExcluded(rel) || strings.HasPrefix(d.Name(), ".")) {
				return fs.SkipDir
			}

			return nil
		}

		name := d.Name()
		if strings.HasPrefix(name, ".") || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			return nil
		}

		files = append(files, rel)

		data, err := os.ReadFile(path) // #nosec G304 -- path comes from the repo walk
		if err != nil {
			return fmt.Errorf("readFile %s: %w", path, err)
		}

		if dir := filepath.Dir(path); bytes.Contains(data, []byte(logrusImport)) && !seen[dir] {
			seen[dir] = true
			dirs = append(dirs, dir)
		}

		return nil
	})
	if err != nil {
		return nil, nil, fmt.Errorf("walkDir: %w", err)
	}

	slices.Sort(dirs)

	return files, dirs, nil
}

func logsExcluded(rel string) bool {
	for _, ex := range logsExcludedDirs {
		if rel == ex || strings.HasPrefix(rel, ex+"/") {
			return true
		}
	}

	return false
}

// logsPkgName returns the package name declared in dir, preferring a file that
// is neither generated nor a test, so that a stale log.go cannot pin a wrong
// name. It returns an empty name when no Go file declares a package.
func logsPkgName(dir string) (string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return "", fmt.Errorf("readDir %s: %w", dir, err)
	}

	var preferred, fallback []string
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") {
			continue
		}

		fallback = append(fallback, name)
		if name != logsFileName && !strings.HasSuffix(name, "_test.go") {
			preferred = append(preferred, name)
		}
	}

	if len(preferred) == 0 {
		preferred = fallback
	}

	// os.ReadDir sorts by name, so the pick is deterministic.
	for _, name := range preferred {
		data, err := os.ReadFile(filepath.Join(dir, name)) // #nosec G304 -- path comes from the repo walk
		if err != nil {
			return "", fmt.Errorf("readFile %s: %w", name, err)
		}

		if pkg := pkgClause(data); pkg != "" {
			return pkg, nil
		}
	}

	return "", nil
}

// pkgClause returns the name of the first package clause in data.
func pkgClause(data []byte) string {
	for line := range strings.SplitSeq(string(data), "\n") {
		rest, ok := strings.CutPrefix(line, "package ")
		if !ok {
			continue
		}

		if fields := strings.Fields(rest); len(fields) > 0 {
			return fields[0]
		}
	}

	return ""
}
